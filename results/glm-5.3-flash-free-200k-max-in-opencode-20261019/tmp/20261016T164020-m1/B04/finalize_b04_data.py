def svd(source_id, title, org, url, published, accessed, note=None,
        partial=None, upd_reason=None):
    reasons = {}
    if published is None:
        reasons["published_or_updated_at"] = upd_reason or "归档摘录未含发布/更新日期字段"
    else:
        reasons["published_or_updated_at"] = "已取得"
    return {
        "source_id": source_id,
        "title": title,
        "author_or_organization": org,
        "url_or_path": url,
        "published_or_updated_at": published,
        "accessed_at": "2026-10-18 " + accessed + " " + TZ,
        "access_evidence": {
            "path_base": "suite_root",
            "path": S_REL + (ARCH.get(source_id) or ""),
            "format": "webfetch 原文摘录存档（含 标题/机构/访问时间/关键原文明文）",
        },
        "unavailable_field_reasons": reasons,
        "read_status": partial or "full-content fetched & read",
        "note": note,
    }


