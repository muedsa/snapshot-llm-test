'use strict';
// Synthetic isolated ledger regression. This is not real task execution evidence.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {createSuite, sha256} = require('./suite.cjs');
const fixture = path.join(__dirname, 'artifact-dedupe-fixture-000001');
fs.mkdirSync(fixture, {recursive: false});
const run_id = 'synthetic-regression-only';
const outputSuite = path.join(fixture, 'outputs', run_id, '_suite');
const tempSuite = path.join(fixture, 'tmp', run_id, '_suite');
fs.mkdirSync(outputSuite, {recursive: true});
fs.mkdirSync(path.join(tempSuite, 'checkpoints'), {recursive: true});
const image1 = path.join(fixture, 'one.png');
const a = {id:'A05-artifact-000001', image_path:image1, title:'original evidence'};
const clone = {...a};
const b = {id:'A05-artifact-000002', image_path:path.join(fixture, 'two.png')};
const initial = {run_id, status:'in_progress', profile:'all', started_at:new Date().toISOString(), tasks:[{id:'A05',status:'in_progress', started_at:new Date().toISOString(), artifacts:[a,clone], visual_review_evidence:['view-1']}]};
const originalBytes = Buffer.from(JSON.stringify(initial,null,2)+'\n');
const historic = path.join(tempSuite, 'checkpoints', 'state-000001.json');
fs.writeFileSync(historic,originalBytes,{flag:'wx'});
fs.writeFileSync(path.join(outputSuite,'suite-state.json'),originalBytes,{flag:'wx'});
const suite=createSuite({root:fixture,run_id,config:{output_root:'outputs',temp_root:'tmp',asset_policy_by_track:{advanced:'dsl_only'}},catalog:{suite_version:'synthetic-regression-only',task_order:['A05'],tasks:[{id:'A05',title:'Synthetic fixture',track:'advanced',minimum_final_pngs:1}]}});
suite.taskCheckpoint('A05',{artifacts:[],visual_review_evidence:['view-1']});
assert.equal(suite.readState().tasks[0].artifacts.length,1);
assert.equal(suite.readState().tasks[0].visual_review_evidence.length,1);
suite.taskEnd('A05','partial',{artifacts:[{...a},{id:'different-id-same-image',image_path:image1.toUpperCase()},b]});
const final=suite.readState().tasks[0];
assert.equal(final.artifacts.length,2);
assert.equal(final.artifacts[0].title,'original evidence');
assert.equal(final.artifacts[1].id,b.id);
assert.equal(sha256(fs.readFileSync(historic)),sha256(originalBytes));
const result={tested_at:new Date().toISOString(),scope:'Synthetic isolated ledger; not actual A05 execution or service calls',checks:{checkpoint_removes_deserialized_duplicate:true,end_removes_clone_and_case_variant_same_image:true,independent_image_retained:true,primitive_review_ids_unchanged:true,historical_fixture_snapshot_unchanged:true},fixture};
fs.writeFileSync(path.join(__dirname,'artifact-dedupe-verification-000001.json'),JSON.stringify(result,null,2)+'\n',{flag:'wx'});
process.stdout.write(JSON.stringify(result)+'\n');
