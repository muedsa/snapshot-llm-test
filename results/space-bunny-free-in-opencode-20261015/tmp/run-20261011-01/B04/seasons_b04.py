def parse(rows: str = ROWS):
    """返回 (years, J-D, DJF, MAM, JJA, SON) 六条等长列表。"""
    years, jdn, djf, mam, jja, son = [], [], [], [], [], []
    for raw in rows.strip().splitlines():
        parts = raw.split()
        if len(parts) != 6:
            raise ValueError(f"行字段数不是 6：{raw!r}")
        years.append(int(parts[0]))
        jdn.append(float(parts[1]))
        djf.append(float(parts[2]))
        mam.append(float(parts[3]))
        jja.append(float(parts[4]))
        son.append(float(parts[5]))
    assert years == list(range(1880, 2026)), "年份必须连续覆盖 1880–2025"
    return years, jdn, djf, mam, jja, son


