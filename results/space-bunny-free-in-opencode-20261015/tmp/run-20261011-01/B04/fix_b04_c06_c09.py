# B04-06 修正：15 行 × 行距 44 从 268 排到 918，而画布只有 820 ——
#   **1990s 之后整段都在画布外**，汇总块（820+）更是完全没出现，图上只剩前十行全是 0，
#   而标题却在说「从 0 到 5」，标题与图完全对不上。
#   → 行距 44→36、画布 820→1020：末行 772–804，汇总块 824–936，脚注横线 960。
#
# B04-09 修正：汇总块排在 764、高 104 → 764–868，画布 860，同样出界；
#   而脚注在 816，直接压住块里那两行数值。→ 画布 860→940。
# 启动基准：总任务根 (suite_root)。用法：python fix_b04_c06_c09.py
from pathlib import Path

p = Path(__file__).parent / "build_b04.py"
s = p.read_text(encoding="utf-8")

subs = [
    # ── case-06 ──
    ("def c06():\n    W, H = 1040, 820", "def c06():\n    W, H = 1040, 1020"),
    ("    PX, PY, PW = 210, 268, 640\n    rh = 44",
     "    PX, PY, PW = 210, 268, 640\n"
     "    # 行距 44 时 15 行排到 918，画布 820 → 后五行与整个汇总块都在画布外。\n"
     "    # 收到 36 并把画布加到 1020：末行 772–804，汇总块 824–936，脚注横线 960。\n"
     "    rh = 36"),
    # ── case-09 ──
    ("def c09():\n    W, H = 1240, 860", "def c09():\n    W, H = 1240, 940"),
]
for a, bb in subs:
    assert s.count(a) == 1, a[:46]
    s = s.replace(a, bb)
p.write_text(s, encoding="utf-8")
print("c06 / c09 fixed")