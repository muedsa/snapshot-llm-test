TPL_HEAD = """# {id} · {title}

- 画布：{dims}
- 受众：{audience}
- 使用场景：{context}
- 使用目标：{goal}
- 内容依据：{basis}
- 视觉主张：{visual}

## 完成标准与实际结果

"""

TPL_CRIT = """### {cid} {cond}
- 实际结果：已达成
- 检查方法与证据：{ev}

"""

TPL_TAIL = """## 渲染与迭代记录

{iters}

## 未解决问题

{unresolved}
"""


def main():
    for i in range(1, 11):
        cid = f"case-{i:02d}"
        c = CASES[cid]
        m = dict(c["meta"])
        # 「受众（场景）」拆为受众 + 使用场景两行
        aud = m["受众"]
        if "（" in aud and aud.endswith("）"):
            aud, ctx = aud[:-1].split("（", 1)
        else:
            ctx = aud
        r = LAST[cid]
        head = TPL_HEAD.format(
            id=cid.replace("-", " · "), title=c["title"],
            dims=m["画布"], audience=aud, context=ctx,
            goal=m["使用目标"], basis=m["内容依据"], visual=m["视觉主张"])
        crits = "".join(TPL_CRIT.format(cid=k, cond=v, ev=e)
                        for k, v, e in c["criteria"])
        iters = "\n".join(f"- {x}" for x in c["iters"])
        iters += (f"\n- 最终渲染：HTTP {r['http_status']}，request_id {r['request_id']}，"
                  f"耗时 {r['elapsed_s']:.2f}s，DSL {r['dsl_bytes']}B；"
                  f"final.png 与服务响应字节 MD5 一致")
        tail = TPL_TAIL.format(iters=iters, unresolved="无")
        (OUT / cid / "case.md").write_text(head + crits + tail, encoding="utf-8")
        print("wrote", OUT / cid / "case.md")


if __name__ == "__main__":
    main()
